-- Agrega tablas y columnas para funcionalidades de negocio:
-- - Registro de usuarios con referidos
-- - CRUD de productos (borrado lógico)
-- - Gestión de pedidos con estados
-- - Ledger de comisiones y liquidaciones
-- Idempotente: usa IF NOT EXISTS donde sea posible

-- ===== ALTER TABLAS EXISTENTES =====

-- Usuarios: agregar nombre, activo, referido_id, creado_en
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'usuarios' AND column_name = 'nombre'
    ) THEN
        ALTER TABLE usuarios ADD COLUMN nombre VARCHAR(150);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'usuarios' AND column_name = 'activo'
    ) THEN
        ALTER TABLE usuarios ADD COLUMN activo BOOLEAN DEFAULT true;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'usuarios' AND column_name = 'creado_en'
    ) THEN
        ALTER TABLE usuarios ADD COLUMN creado_en TIMESTAMP DEFAULT NOW();
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'usuarios' AND column_name = 'referido_id'
    ) THEN
        ALTER TABLE usuarios ADD COLUMN referido_id INTEGER REFERENCES referidos(id);
    END IF;
END $$;

-- Referidos: agregar código único para links de invitación
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'referidos' AND column_name = 'codigo'
    ) THEN
        ALTER TABLE referidos ADD COLUMN codigo VARCHAR(20) UNIQUE;
    END IF;
END $$;

-- Productos: agregar activo para borrado lógico
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'productos' AND column_name = 'activo'
    ) THEN
        ALTER TABLE productos ADD COLUMN activo BOOLEAN DEFAULT true;
    END IF;
END $$;

-- Pedidos: agregar estado y usuario_id
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'pedidos' AND column_name = 'estado'
    ) THEN
        ALTER TABLE pedidos ADD COLUMN estado VARCHAR(20) DEFAULT 'pendiente';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'pedidos' AND column_name = 'usuario_id'
    ) THEN
        ALTER TABLE pedidos ADD COLUMN usuario_id INTEGER REFERENCES usuarios(id);
    END IF;
END $$;

-- ===== NUEVAS TABLAS =====

-- Comisiones: ledger de cada comisión generada por pedido
CREATE TABLE IF NOT EXISTS comisiones (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        INTEGER NOT NULL REFERENCES pedidos(id),
    referido_id      INTEGER NOT NULL REFERENCES referidos(id),
    nivel            INTEGER NOT NULL CHECK (nivel >= 1 AND nivel <= 3),
    porcentaje       INTEGER NOT NULL CHECK (porcentaje > 0),
    monto            NUMERIC(12,2) NOT NULL CHECK (monto >= 0),
    estado           VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'pagada', 'revertida')),
    liquidacion_id   INTEGER,
    creado_en        TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_comisiones_referido ON comisiones(referido_id);
CREATE INDEX IF NOT EXISTS idx_comisiones_pedido ON comisiones(pedido_id);
CREATE INDEX IF NOT EXISTS idx_comisiones_estado ON comisiones(estado);

-- Liquidaciones: pagos a distribuidores
CREATE TABLE IF NOT EXISTS liquidaciones (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referido_id  INTEGER NOT NULL REFERENCES referidos(id),
    total        NUMERIC(12,2) NOT NULL CHECK (total >= 0),
    estado       VARCHAR(20) NOT NULL DEFAULT 'aprobada' CHECK (estado IN ('aprobada', 'pagada', 'cancelada')),
    creado_en    TIMESTAMP NOT NULL DEFAULT NOW(),
    pagada_en    TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_liquidaciones_referido ON liquidaciones(referido_id);

