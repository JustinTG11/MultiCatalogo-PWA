-- MultiCatálogo - esquema y datos iniciales (PostgreSQL 16).
-- Docker lo ejecuta automáticamente la primera vez que se crea el contenedor.
-- (Si ya tienes la base creada de fases anteriores, aplica database/002_checkout.sql en lugar de borrar el volumen.)

DROP TABLE IF EXISTS pedido_items;
DROP TABLE IF EXISTS pedidos;
DROP TABLE IF EXISTS usuarios;
DROP TABLE IF EXISTS productos;
DROP TABLE IF EXISTS referidos;

-- ---------- referidos (árbol multinivel auto-referenciado) ----------
-- id sin autoincremento: el nodo raíz ("Tú") tiene id = 0 y parent_id NULL.
-- ventas: volumen de ventas del nodo. comisiones: saldo acumulado que ganó por las compras de su red.
CREATE TABLE referidos (
  id         INTEGER PRIMARY KEY,
  nombre     VARCHAR(150)  NOT NULL,
  nivel      INTEGER       NOT NULL CHECK (nivel >= 0),
  ventas     NUMERIC(12,2) NOT NULL DEFAULT 0,
  comisiones NUMERIC(12,2) NOT NULL DEFAULT 0,
  parent_id  INTEGER REFERENCES referidos(id)
);
CREATE INDEX idx_referidos_parent ON referidos(parent_id);

-- ---------- usuarios ----------
-- password en texto plano TEMPORALMENTE (se cambiará por hash en una fase posterior).
-- token: se valida en el middleware de autenticación (Authorization: Bearer <token>).
-- referido_id: nodo del árbol que representa a este usuario (para pagar comisiones a sus ascendentes).
CREATE TABLE usuarios (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       VARCHAR(150) NOT NULL UNIQUE,
  password    VARCHAR(100) NOT NULL,
  rol         VARCHAR(20)  NOT NULL CHECK (rol IN ('admin', 'cliente')),
  token       VARCHAR(100) NOT NULL,
  referido_id INTEGER REFERENCES referidos(id)
);

-- ---------- productos ----------
-- stock simulado: se descuenta en cada compra; el CHECK impide que quede negativo.
CREATE TABLE productos (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(150)  NOT NULL,
  descripcion TEXT          NOT NULL,
  precio      NUMERIC(10,2) NOT NULL CHECK (precio >= 0),
  categoria   VARCHAR(50)   NOT NULL,
  img         TEXT          NOT NULL,
  galeria     TEXT[]        NOT NULL DEFAULT '{}',
  stock       INTEGER       NOT NULL DEFAULT 100 CHECK (stock >= 0)
);

-- ---------- pedidos y detalle (Fase 4: checkout transaccional) ----------
CREATE TABLE pedidos (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id            INTEGER       NOT NULL REFERENCES usuarios(id),
  cliente_nombre        VARCHAR(150)  NOT NULL,
  cliente_email         VARCHAR(150)  NOT NULL,
  direccion             VARCHAR(250)  NOT NULL,
  ciudad                VARCHAR(100)  NOT NULL,
  telefono              VARCHAR(30)   NOT NULL,
  metodo_pago           VARCHAR(50)   NOT NULL,
  total                 NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
  comisiones_procesadas BOOLEAN       NOT NULL DEFAULT FALSE,
  creado_en             TIMESTAMPTZ   NOT NULL DEFAULT NOW()
);

CREATE TABLE pedido_items (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id       INTEGER       NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
  producto_id     INTEGER       NOT NULL REFERENCES productos(id),
  cantidad        INTEGER       NOT NULL CHECK (cantidad > 0),
  precio_unitario NUMERIC(10,2) NOT NULL CHECK (precio_unitario >= 0),
  UNIQUE (pedido_id, producto_id)
);

-- ---------- índices (los mismos que añade la migración 003_seguridad.sql a bases existentes) ----------
-- referidos(parent_id) ya se creó arriba (idx_referidos_parent).
CREATE INDEX idx_pedidos_cliente_email ON pedidos(cliente_email);
CREATE INDEX idx_pedido_items_pedido   ON pedido_items(pedido_id);
CREATE INDEX idx_productos_categoria   ON productos(categoria);

